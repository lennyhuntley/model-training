def prep_pipeline_from_raw(ds_raw: tf.data.Dataset, num_classes: int, training: bool):
    # Select percent
    if PERCENT_TO_USE < 1.0:
        take_n = int(1_000_000_000 * PERCENT_TO_USE)  # overshoot; we'll rely on cardinality if known
        ds_raw = ds_raw.take(take_n)

    def _prep(img, lbl):
        img = tf.image.convert_image_dtype(img, tf.float32)  # [0,1]
        img = tf.image.resize(img, [IMG_SIZE, IMG_SIZE], antialias=True)
        img = preprocess_inputs(img)
        lbl = tf.one_hot(lbl, num_classes, dtype=tf.float32)
        return img, lbl

    ds = ds_raw.map(_prep, num_parallel_calls=tf.data.AUTOTUNE)

    if training:
        # Optional cache (memory permitting)
        ds = ds.cache()
        # Non-deterministic for speed
        opts = tf.data.Options()
        opts.experimental_deterministic = False
        ds = ds.with_options(opts)
        # Shuffle, batch, prefetch
        ds = ds.shuffle(8192, reshuffle_each_iteration=True)

    ds = ds.batch(BATCH_SIZE, drop_remainder=training)
    ds = ds.prefetch(tf.data.AUTOTUNE)
    return ds

