#@title 3.1 Model builder
def build_model(num_classes: int):
    inputs = layers.Input(shape=(IMG_SIZE, IMG_SIZE, 3), dtype="float32")
    x = make_augmenter()(inputs)  # training-only aug
    x = layers.Lambda(preprocess_inputs, name="preprocess")(x)

    base = keras.applications.MobileNetV2(
        include_top=False,
        input_shape=(IMG_SIZE, IMG_SIZE, 3),
        weights="imagenet"
    )
    base.trainable = False

    feats = base(x, training=False)
    feats = layers.GlobalAveragePooling2D(name="gap")(feats)
    feats = layers.Dropout(0.2, name="drop")(feats)

    # Keep final dense in float32; export probs as float32 for metrics/loss stability
    logits = layers.Dense(num_classes, dtype="float32", name="logits")(feats)
    probs  = layers.Activation("softmax", dtype="float32", name="probs")(logits)

    model = keras.Model(inputs, probs, name="mobilenetv2_nabirds_k3")
    model._backbone = base
    return model

def unfreeze_top(model: keras.Model, ratio: float = 0.75, freeze_bn: bool = True):
    base = getattr(model, "_backbone", None)
    if base is None:
        return
    n = len(base.layers)
    cut = int(n * ratio)
    for i, layer in enumerate(base.layers):
        trainable = (i >= cut)
        layer.trainable = trainable
        if freeze_bn and isinstance(layer, (layers.BatchNormalization,)):
            layer.trainable = False

