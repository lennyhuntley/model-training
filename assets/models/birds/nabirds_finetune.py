metrics = ["accuracy", TopKCategoricalAccuracy(k=5, name="top5")]

model.compile(
    optimizer=Adam(LR_WARMUP),
    loss=loss,
    metrics=metrics
)

# Compute steps explicitly from the index lists created in 4.1
n_train = len(train_indices)
n_val   = len(val_indices)

# training dataloader uses drop_remainder=True → floor division
steps_per_epoch = max(1, n_train // BATCH_SIZE)
# validation keeps the remainder → ceil
val_steps = max(1, math.ceil(n_val / BATCH_SIZE))

print("Warmup steps_per_epoch:", steps_per_epoch, "val_steps:", val_steps)

# IMPORTANT: repeat() makes datasets endless; steps_* bound each epoch
history_warm = model.fit(
    train_ds.repeat(),
    validation_data=val_ds.repeat(),
    epochs=EPOCHS_WARMUP,
    steps_per_epoch=steps_per_epoch,
    validation_steps=val_steps,
    verbose=1
)

#@title 4.3 Fine-tune
unfreeze_top(model, ratio=FREEZE_RATIO, freeze_bn=True)

total_ft_steps = (steps_per_epoch or 1000) * EPOCHS_FINETUNE
lr_schedule = CosineDecay(initial_learning_rate=LR_FINE, decay_steps=total_ft_steps, alpha=0.1)

